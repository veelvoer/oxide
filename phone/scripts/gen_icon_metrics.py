#!/usr/bin/env python3
"""Optical offsets of the phone's icons, written to src/icon_metrics.rs: python3 scripts/gen_icon_metrics.py > src/icon_metrics.rs
Each glyph is rasterised; the point the eye takes as its center is the average of its box middle and its mass middle.
The offset (in em) is how far that point sits from where egui draws the glyph (advance middle, line middle); an icon is
drawn at `center - offset * size`."""
import re
import numpy as np
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

S = 512
src = open("src/ui.rs").read()
cps = sorted(set(int(m, 16) for m in re.findall(r"\\u\{([0-9A-Fa-f]+)\}", src[: src.find("pub fn icon_at")])))


def table(path):
    font = ImageFont.truetype(path, S)
    tt = TTFont(path)
    asc, desc, upem = tt["hhea"].ascent, tt["hhea"].descent, tt["head"].unitsPerEm
    cmap = tt.getBestCmap()
    rows = []
    for cp in cps:
        if cp not in cmap:
            continue
        im = Image.new("L", (S * 3, S * 3), 0)
        ImageDraw.Draw(im).text((S, S), chr(cp), font=font, fill=255, anchor="ls")
        a = np.array(im).astype(float)
        m = a > 90
        ys, xs = np.where(m)
        if not len(xs):
            continue
        box = ((xs.min() + xs.max()) / 2, (ys.min() + ys.max()) / 2)
        yy, xx = np.mgrid[0 : a.shape[0], 0 : a.shape[1]]
        w = a * m
        mass = ((w * xx).sum() / w.sum(), (w * yy).sum() / w.sum())
        x = ((box[0] + mass[0]) / 2 - S - font.getlength(chr(cp)) / 2) / S
        y = ((box[1] + mass[1]) / 2 - S + (asc + desc) / 2 / upem * S) / S
        rows.append((cp, x, y))
    return rows


print("//! Generated by scripts/gen_icon_metrics.py: optical offsets of the icons (in em). Draw an icon at `center - offset * size`")
print("//! and its ink looks centered, not just its box.\n")
for name, path in (("ICON_OFFSETS", "assets/fonts/Phosphor.ttf"), ("ICON_OFFSETS_FILL", "assets/fonts/Phosphor-Fill.ttf")):
    print(f"pub const {name}: &[(u32, f32, f32)] = &[")
    for cp, x, y in table(path):
        print(f"    (0x{cp:04X}, {x:.4f}, {y:.4f}),")
    print("];\n")
