/// Draw icon `name` at `size` points, tinted with `color`.
pub fn icon(ui: &mut Ui, name: &str, size: f32, color: Color32) {
    if let Some(bytes) = svg(name).or_else(|| svg("circle-small")) {
        ui.add(egui::Image::from_bytes(format!("bytes://mdi-{name}.svg"), bytes).tint(color).fit_to_exact_size(vec2(size, size)));
    } else {
        ui.allocate_space(vec2(size, size));
    }
}

/// Paint an icon centered in `rect` (for custom-drawn widgets).
pub fn paint(ui: &Ui, name: &str, rect: egui::Rect, color: Color32) {
    if let Some(bytes) = svg(name).or_else(|| svg("circle-small")) {
        egui::Image::from_bytes(format!("bytes://mdi-{name}.svg"), bytes).tint(color).paint_at(ui, rect);
    }
}
