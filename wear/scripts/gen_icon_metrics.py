#!/usr/bin/env python3
"""Measure how far each icon (and each font's capitals) sits from the point it is drawn at, and write src/icon_metrics.rs.

Run `OXIDE_WATCH_CALIB=icons oxide-watch-desktop` and `OXIDE_WATCH_CALIB=text oxide-watch-desktop` (zoom 2 in a 450 px
window), take a screenshot of each and pass them: gen_icon_metrics.py icons.png text.png > src/icon_metrics.rs
The offsets are in em (a share of the font size): an icon is drawn at (center - offset * size), so that its ink, judged by
the eye (between the middle of its box and the middle of its mass), lands on the center."""
import sys
import numpy as np
from PIL import Image

ICONS = [0xE32E, 0xE3D4, 0xE272, 0xE3DA, 0xE2FA, 0xE330, 0xE44A, 0xE45C, 0xE3D0, 0xE5A4, 0xE5A6, 0xE058, 0xE182, 0xE0AE, 0xE1AC, 0xE094, 0xE33A,
         0xE464, 0xE434, 0xE156, 0xE13A, 0xE32A, 0xE1E0, 0xE396, 0xE4F6]


def window(path):
    im = np.array(Image.open(path).convert("L")).astype(float)
    ys, xs = np.where(im == 0)
    return im[ys.min():ys.max() + 1, xs.min():xs.max() + 1]


def ink(cell):
    m = cell > 90
    ys, xs = np.where(m)
    w = cell * m
    box = ((xs.min() + xs.max()) / 2.0, (ys.min() + ys.max()) / 2.0)
    yy, xx = np.mgrid[0:cell.shape[0], 0:cell.shape[1]]
    mass = ((w * xx).sum() / w.sum(), (w * yy).sum() / w.sum())
    return box, mass


icons = window(sys.argv[1])
text = window(sys.argv[2])
size_px = 26 * 2.0
rows = []
for i, cp in enumerate(ICONS):
    cx, cy = 45 + (i % 5) * 90, 45 + (i // 5) * 90
    cell = icons[cy - 45:cy + 45, cx - 45:cx + 45]
    box, mass = ink(cell)
    # judged by the eye: the middle of the box and the middle of the mass count the same
    ox = ((box[0] + mass[0]) / 2.0 - 45) / size_px
    oy = ((box[1] + mass[1]) / 2.0 - 45) / size_px
    rows.append((cp, ox, oy))
print("//! Generated by scripts/gen_icon_metrics.py: optical offsets of the icons and the fonts' capitals (in em).")
print("//! Draw an icon at `center - offset * size` and its ink looks centered, not just its box.\n")
print("pub const ICON_OFFSETS: &[(u32, f32, f32)] = &[")
for cp, ox, oy in rows:
    print(f"    (0x{cp:X}, {ox:.4f}, {oy:.4f}),")
print("];\n")
names = ["REGULAR", "MEDIUM", "SEMIBOLD"]
print("/// Where the capitals of each font sit below (+) the middle of its line box, in em.")
for n, name in enumerate(names):
    cy = 90 + n * 120
    cell = text[cy - 60:cy + 60, :]
    box, _ = ink(cell)
    print(f"pub const CAP_DY_{name}: f32 = {(box[1] - 60) / 60.0:.4f};")
